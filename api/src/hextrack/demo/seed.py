def _is_demo_match(column: Any) -> Any:
    return column.startswith(DEMO_MATCH_PREFIX, autoescape=True)


def _is_demo_puuid(column: Any) -> Any:
    return column.startswith(DEMO_PUUID_PREFIX, autoescape=True)


async def delete_demo_data(session: AsyncSession) -> int:
    """Delete every ``DEMO_`` match (with its participants), every ``demo-`` summoner (with
    its rank snapshots) and bot events that refer to either. Returns the number of matches
    deleted. Real data is never touched. Does not commit."""
    await session.execute(
        delete(BotEvent).where(
            or_(
                _is_demo_puuid(BotEvent.payload["puuid"].astext),
                _is_demo_match(BotEvent.payload["match_id"].astext),
            )
        )
    )
    await session.execute(delete(MatchParticipant).where(_is_demo_match(MatchParticipant.match_id)))
    result = await session.execute(
        delete(Match).where(_is_demo_match(Match.match_id)).returning(Match.match_id)
    )
    deleted = len(result.all())
    await session.execute(delete(RankSnapshot).where(_is_demo_puuid(RankSnapshot.puuid)))
    await session.execute(delete(Summoner).where(_is_demo_puuid(Summoner.puuid)))
    return deleted


async def clear_demo(settings: Settings) -> int:
    """Delete all demo data (see :func:`delete_demo_data`) without seeding anything new, e.g.
    once real games have been imported. Returns the number of demo matches deleted."""
    engine = make_async_engine(settings, pool_size=1, max_overflow=0)
    try:
        async with make_session_factory(engine)() as session:
            deleted = await delete_demo_data(session)
            await session.commit()
    finally:
        await engine.dispose()
    logger.info("deleted %d demo matches and all demo summoners", deleted)
    return deleted


def _load_scorer(model_dir: Path) -> Scorer | None:
    """The active AI model, or None (demo data is then stored unscored)."""
    from hextrack.hextrack_ai.inference import Scorer

    try:
        scorer = Scorer.load(model_dir)
    except Exception:
        logger.exception("could not load the AI model from %s; seeding without scores", model_dir)
        return None
    if scorer is None:
        logger.info("no AI model in %s; demo matches are stored unscored", model_dir)
    return scorer


async def _insert_summoners(session: AsyncSession, dataset: DemoDataset, platform: str) -> set[str]:
    """Insert missing demo summoners; returns the demo puuids present afterwards."""
    rows = [
        {
            "puuid": s.puuid,
            "game_name": s.game_name,
            "tag_line": s.tag_line,
            "platform": platform,
            "profile_icon_id": s.profile_icon_id,
            "summoner_level": s.summoner_level,
            "is_tracked": s.is_tracked,
            "tracked_since": s.tracked_since,
            "last_refreshed_at": s.last_refreshed_at,
            "backfilled_at": s.backfilled_at,
        }
        for s in dataset.summoners
    ]
    for chunk_start in range(0, len(rows), 500):
        chunk = rows[chunk_start : chunk_start + 500]
        # No conflict target: skips both an existing puuid and a Riot ID already used by a
        # real account.
        await session.execute(insert(Summoner).values(chunk).on_conflict_do_nothing())
    wanted = [s.puuid for s in dataset.summoners]
    present = set(
        (await session.scalars(select(Summoner.puuid).where(Summoner.puuid.in_(wanted)))).all()
    )
    missing = len(wanted) - len(present)
    if missing:
        logger.warning("%d demo summoners clash with existing Riot IDs and were skipped", missing)
    return present


async def _insert_snapshots(session: AsyncSession, dataset: DemoDataset, present: set[str]) -> int:
    """Insert rank history for demo summoners that have none yet (keeps reruns idempotent)."""
    have_history = set(
        (
            await session.scalars(
                select(RankSnapshot.puuid)
                .where(_is_demo_puuid(RankSnapshot.puuid))
                .group_by(RankSnapshot.puuid)
            )
        ).all()
    )
    rows = [
        {
            "puuid": s.puuid,
            "queue_type": s.queue_type,
            "tier": s.tier,
            "rank": s.rank,
            "lp": s.lp,
            "wins": s.wins,
            "losses": s.losses,
            "rank_value": s.rank_value,
            "taken_at": s.taken_at,
            "is_heartbeat": s.is_heartbeat,
        }
        for s in dataset.snapshots
        if s.puuid in present and s.puuid not in have_history
    ]
    for chunk_start in range(0, len(rows), 1000):
        await session.execute(insert(RankSnapshot).values(rows[chunk_start : chunk_start + 1000]))
    return len(rows)


async def _real_riot_ids(
    session: AsyncSession, dataset: DemoDataset, platform: str
) -> set[tuple[str, str]]:
    """Riot IDs in ``dataset`` that already belong to non-demo summoners on ``platform``."""
    wanted = {(s.game_name.lower(), s.tag_line.lower()) for s in dataset.summoners}
    found: set[tuple[str, str]] = set()
    pairs = sorted(wanted)
    for start in range(0, len(pairs), 500):
        chunk = pairs[start : start + 500]
        rows = await session.execute(
            select(Summoner.game_name, Summoner.tag_line).where(
                tuple_(func.lower(Summoner.game_name), func.lower(Summoner.tag_line)).in_(chunk),
                Summoner.platform == platform,
                ~_is_demo_puuid(Summoner.puuid),
            )
        )
        found.update(riot_id_key(name, tag) for name, tag in rows.all())
    return found


async def _dataset_avoiding_real_accounts(
    session: AsyncSession,
    *,
    players: int,
    matches: int,
    seed: int,
    now: datetime | None,
    platform: str,
) -> DemoDataset:
    """:func:`build_dataset`, regenerated with clashing Riot IDs reserved until no demo
    summoner shares a Riot ID with a real account."""
    reserved: set[tuple[str, str]] = set()
    for _attempt in range(5):
        dataset = build_dataset(
            players=players,
            matches=matches,
            seed=seed,
            now=now,
            platform=platform,
            reserved=reserved,
        )
        clashes = await _real_riot_ids(session, dataset, platform) - reserved
        if not clashes:
            return dataset
        logger.info("%d demo Riot IDs belong to real accounts; regenerating", len(clashes))
        reserved |= clashes
    return dataset


async def seed_demo(
    settings: Settings,
    *,
    reset: bool,
    players: int = 8,
    matches: int = 220,
    seed: int = 7,
    now: datetime | None = None,
) -> SeedReport:
    """Create ``players`` tracked summoners (plus the opponents they meet), ``matches``
    synthetic ranked games (10 participants each, generated from ``random.Random(seed)``) and
    their rank history, all through the real ingestion path. Games are scored when an AI
    model is available in ``settings.model_dir``.

    With ``reset``, existing demo data (``DEMO_`` matches, ``demo-`` summoners, their rank
    snapshots and bot events) is deleted first; real data is never touched. Without it the
    call is idempotent: existing demo matches and rank histories are left as they are.
    Demo Riot IDs never collide with stored real accounts: clashing opponents are renamed
    and a clashing roster member gets a ``DEMO`` tag. ``now`` pins the clock (tests); games
    end before the latest 05:00 UTC, so a seed gives the same games at any time of day.
    """
    engine = make_async_engine(settings, pool_size=2, max_overflow=0)
    try:
        factory = make_session_factory(engine)
        async with factory() as session:
            dataset = await _dataset_avoiding_real_accounts(
                session,
                players=players,
                matches=matches,
                seed=seed,
                now=now,
                platform=settings.riot_platform,
            )
        scorer = _load_scorer(settings.model_dir)
        # Offline client: nothing here talks to Riot, and a stray call fails fast.
        async with RiotClient(settings.model_copy(update={"riot_api_key": None})) as riot:
            ctx = IngestContext(
                settings=settings, session_factory=factory, riot=riot, scorer=scorer
            )
            async with factory() as session:
                deleted = 0
                if reset:
                    deleted = await delete_demo_data(session)
                    await session.commit()
                    logger.info("deleted %d demo matches and all demo summoners", deleted)

                present = await _insert_summoners(session, dataset, settings.riot_platform)
                await session.commit()

                created = participants = scored = 0
                for i, raw in enumerate(dataset.matches, start=1):
                    result = await ingest_match_json(ctx, session, raw, enqueue_events=False)
                    if result.created:
                        created += 1
                        participants += result.participants
                        scored += 1 if result.scored else 0
                    if i % COMMIT_EVERY == 0:
                        await session.commit()
                await session.commit()

                snapshots = await _insert_snapshots(session, dataset, present)
                await session.commit()
    finally:
        await engine.dispose()

    tracked = sum(1 for s in dataset.summoners if s.is_tracked and s.puuid in present)
    report = SeedReport(
        players=tracked,
        matches=created,
        participants=participants,
        rank_snapshots=snapshots,
        reset=reset,
        opponents=len(present) - tracked,
        scored_matches=scored,
        deleted_matches=deleted,
    )
    logger.info(
        "demo seed: %d tracked players, %d opponents, %d new matches (%d scored), "
        "%d rank snapshots",
        report.players,
        report.opponents,
        report.matches,
        report.scored_matches,
        report.rank_snapshots,
    )
    return report
