"""Seed a realistic synthetic dataset through the real ingestion path (owner: B6).

There is no Riot API key in development, so the web UI is built and demoed against data made
here. :func:`build_dataset` is pure and deterministic (``random.Random(seed)`` plus a fixed
``now``); :func:`seed_demo` writes it:

* a tracked roster (:data:`hextrack.demo.names.ROSTER`) of eight friends who often queue
  together (bot-lane duos, flex stacks of 3 or 5), with distinct skill levels, plus a few
  hundred strangers who fill the other slots and keep meeting the roster again;
* ``matches`` ranked games (mostly solo/duo 420, some flex 440) over the last ~100 days in
  evening sessions (laid out relative to the latest 05:00 UTC, so a seed yields the same
  games whenever it runs; only whole-day shifts differ), generated by
  :func:`hextrack.demo.matchgen.generate_match` and stored with
  ``hextrack.ingest.service.ingest_match_json(enqueue_events=False)``, so validation, storage
  and AI scoring (when a model is loaded) are exactly those of live ingestion;
* rank snapshots that follow each tracked player's actual wins and losses: LP gains/losses
  per game, promotions, demotions (with a short demotion shield), a snapshot after every ranked
  game as the poller would take it and a heartbeat every day or two in between.

Everything demo-generated is recognisable: match ids start with ``DEMO_`` and puuids with
``demo-``. ``reset=True`` deletes exactly that data (and bot events that refer to it) and
nothing else, so demo data can live next to real data.
"""

